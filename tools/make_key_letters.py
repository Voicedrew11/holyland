#!/usr/bin/env python3
"""Writes port/gs/shared/key_letters_data.h: the letters printed on the keyboard's keys (port/gs/shared/key_letters.h),
drawn from Barlow Semi Condensed SemiBold (third_party/barlow/). Committed: building the port does not need the font,
only changing the letters does.

    python3 tools/make_key_letters.py [--font third_party/barlow/BarlowSemiCondensed-SemiBold.ttf]

Needs Pillow (pip install pillow). Each letter is a picture of its coverage, CAP rows to a capital's height, with its
place from the pen on the baseline; the arrows are not the font's (it has none) but key_letters.cpp's own shapes.
"""
import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, "third_party", "barlow", "BarlowSemiCondensed-SemiBold.ttf")
OUT = os.path.join(ROOT, "port", "gs", "shared", "key_letters_data.h")
CAP = 48         # (rows a capital is tall)
SUPERSAMPLE = 4  # (drawn this many times as fine, then averaged)
CHARACTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-=[];',./\\`+*"


def letters(font_path):
    """{character: (left, top, width, height, advance, coverage bytes)}, in rows of CAP to a capital"""
    probe = ImageFont.truetype(font_path, 1000)
    cap = -probe.getbbox("H", anchor="ls")[1]
    font = ImageFont.truetype(font_path, round(1000 * CAP * SUPERSAMPLE / cap))
    out = {}
    pad = 2 * SUPERSAMPLE
    for ch in CHARACTERS:
        l, t, r, b = font.getbbox(ch, anchor="ls")
        x0 = (l - pad) // SUPERSAMPLE * SUPERSAMPLE
        y0 = (t - pad) // SUPERSAMPLE * SUPERSAMPLE
        x1 = -(-(r + pad) // SUPERSAMPLE) * SUPERSAMPLE
        y1 = -(-(b + pad) // SUPERSAMPLE) * SUPERSAMPLE
        im = Image.new("L", (x1 - x0, y1 - y0), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        im = im.resize((im.width // SUPERSAMPLE, im.height // SUPERSAMPLE), Image.BOX)
        box = im.getbbox()
        im = im.crop(box)
        left = x0 // SUPERSAMPLE + box[0]
        top = -(y0 // SUPERSAMPLE + box[1])  # (rows above the baseline)
        out[ch] = (left, top, im.width, im.height, round(font.getlength(ch) / SUPERSAMPLE), im.tobytes())
    return out


def c_char(ch):
    return "'\\\\'" if ch == "\\" else "'\\''" if ch == "'" else f"'{ch}'"


def write_header(glyphs):
    lines = [
        "// Generated by tools/make_key_letters.py from Barlow Semi Condensed SemiBold (third_party/barlow/): do not",
        "// edit. The letters port/gs/shared/key_letters.h prints on the keys.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace pcr::key_letters_data {",
        "",
        f"constexpr uint32_t cap_height = {CAP}; // (rows)",
        "",
        "// A letter: its picture's place from the pen on the baseline (left; top, rows above it), in rows",
        "struct Glyph {",
        "    char character;",
        "    int16_t left, top;",
        "    uint16_t width, height, advance;",
        "    uint32_t start; // (in coverage)",
        "};",
        "",
        "static const Glyph glyphs[] = {",
    ]
    start = 0
    for ch, (left, top, width, height, advance, _) in glyphs.items():
        lines.append(f"    {{{c_char(ch)}, {left}, {top}, {width}, {height}, {advance}, {start}}},")
        start += width * height
    lines += ["};", "", "static const uint8_t coverage[] = {"]
    blob = b"".join(g[5] for g in glyphs.values())
    for i in range(0, len(blob), 32):
        lines.append("    " + ",".join(str(v) for v in blob[i:i + 32]) + ",")
    lines += ["};", "", "} // namespace pcr::key_letters_data", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    return len(blob)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--font", default=FONT)
    args = parser.parse_args()
    size = write_header(letters(args.font))
    print(f"wrote {OUT} ({len(CHARACTERS)} letters, {size} bytes of coverage)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
