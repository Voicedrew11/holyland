#!/usr/bin/env python3
"""Writes the letters the menus' buttons are printed with (port/gs/shared/key_letters.h), one header per font:
- port/gs/shared/key_letters_data.h: the keyboard's keys, Barlow Semi Condensed SemiBold (third_party/barlow/);
- port/gs/shared/xbox_letters_data.h: the Xbox buttons' A B X Y, Chakra Petch Bold (third_party/chakra-petch/).
Committed: building the port does not need the fonts, only changing the letters does.

    python3 tools/make_key_letters.py

Needs Pillow (pip install pillow). Each letter is a picture of its coverage, CAP rows to a capital's height, with its
place from the pen on the baseline; the keys' arrows are not the font's (it has none) but key_letters.cpp's own shapes.
A new font is a new entry in FONTS.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAP = 48         # (rows a capital is tall)
SUPERSAMPLE = 4  # (drawn this many times as fine, then averaged)

# (font file, the header written, its namespace, the characters baked, the font's name for the header's comment)
FONTS = [
    ("third_party/barlow/BarlowSemiCondensed-SemiBold.ttf", "port/gs/shared/key_letters_data.h", "key_letters_data",
     "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-=[];',./\\`+*", "Barlow Semi Condensed SemiBold (third_party/barlow/)"),
    ("third_party/chakra-petch/ChakraPetch-Bold.ttf", "port/gs/shared/xbox_letters_data.h", "xbox_letters_data",
     "ABXY", "Chakra Petch Bold (third_party/chakra-petch/)"),
]


def letters(font_path, characters):
    """{character: (left, top, width, height, advance, coverage bytes)}, in rows of CAP to a capital"""
    probe = ImageFont.truetype(font_path, 1000)
    cap = -probe.getbbox("H", anchor="ls")[1]
    font = ImageFont.truetype(font_path, round(1000 * CAP * SUPERSAMPLE / cap))
    out = {}
    pad = 2 * SUPERSAMPLE
    for ch in characters:
        l, t, r, b = font.getbbox(ch, anchor="ls")
        x0 = (l - pad) // SUPERSAMPLE * SUPERSAMPLE
        y0 = (t - pad) // SUPERSAMPLE * SUPERSAMPLE
        x1 = -(-(r + pad) // SUPERSAMPLE) * SUPERSAMPLE
        y1 = -(-(b + pad) // SUPERSAMPLE) * SUPERSAMPLE
        im = Image.new("L", (x1 - x0, y1 - y0), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        im = im.resize((im.width // SUPERSAMPLE, im.height // SUPERSAMPLE), Image.BOX)
        box = im.getbbox()
        im = im.crop(box)
        left = x0 // SUPERSAMPLE + box[0]
        top = -(y0 // SUPERSAMPLE + box[1])  # (rows above the baseline)
        out[ch] = (left, top, im.width, im.height, round(font.getlength(ch) / SUPERSAMPLE), im.tobytes())
    return out


def c_char(ch):
    return "'\\\\'" if ch == "\\" else "'\\''" if ch == "'" else f"'{ch}'"


def write_header(glyphs, out_path, namespace, font_name):
    lines = [
        f"// Generated by tools/make_key_letters.py from {font_name}: do not edit.",
        "// A LetterFont of port/gs/shared/key_letters.h.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        '#include "key_letters.h"',
        "",
        f"namespace pcr::{namespace} {{",
        "",
        f"constexpr uint32_t cap_height = {CAP}; // (rows)",
        "",
        "static const LetterGlyph glyphs[] = {",
    ]
    start = 0
    for ch, (left, top, width, height, advance, _) in glyphs.items():
        lines.append(f"    {{{c_char(ch)}, {left}, {top}, {width}, {height}, {advance}, {start}}},")
        start += width * height
    lines += ["};", "", "static const uint8_t coverage[] = {"]
    blob = b"".join(g[5] for g in glyphs.values())
    for i in range(0, len(blob), 32):
        lines.append("    " + ",".join(str(v) for v in blob[i:i + 32]) + ",")
    lines += ["};", "", f"}} // namespace pcr::{namespace}", ""]
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    return len(blob)


def main() -> int:
    for font, out, namespace, characters, name in FONTS:
        out_path = os.path.join(ROOT, out)
        size = write_header(letters(os.path.join(ROOT, font), characters), out_path, namespace, name)
        print(f"wrote {out_path} ({len(characters)} letters, {size} bytes of coverage)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
