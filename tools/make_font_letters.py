#!/usr/bin/env python3
"""Draws the English letters of the game's fonts again from IPA Mincho, four times as fine, and writes them into
port/gs/shared/font_letters_data.h (committed: building the port needs no font, only changing the letters does).

    python3 tools/make_font_letters.py path/to/ipam.ttf [--preview out.png]

ipam.ttf is IPA Mincho (Fedora: the ipa-mincho-fonts package; elsewhere https://moji.or.jp/ipafont/). The letters it
makes are pictures of text, which the IPA Font License (third_party/ipa-fonts/) lets us ship as they are.

The game's half-width letters are 10 x 20 texel cells (message.c's glyph_sheets, kind 1): ASCII 0x20 + n at column
n % 50, row n / 50, from texel row 460 of the 512 x 512 sheet. In both fonts (font.tmr, menu/font.tmr) a capital stands
from cell row 3 to row 17 (the baseline under row 17) and a descender reaches row 19. Each letter here is drawn into a
cell SCALE times as large: its capitals as tall as the game's, on the same baseline, its advance centred in the cell
and narrowed to fit where it is wider.
"""
import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "port", "gs", "shared", "font_letters_data.h")

SCALE = 4
CELL_W, CELL_H = 10 * SCALE, 20 * SCALE
CAP_TOP, BASELINE = 3 * SCALE, 18 * SCALE  # (rows: a capital's top, the row under its foot)
FIRST, LAST = 0x20, 0x7A  # (the game's cells past z hold no letters)
SUPERSAMPLE = 4  # (each letter drawn this much finer, then averaged: smooth edges)
# The game's letters are bold, about a fifth of a cell's width a stem: IPA Mincho's strokes thickened by this much of a
# game texel on each side
WEIGHT = 0.3
# Cells whose letter in the game is not the ASCII character's: the character drawn there instead
DRAWN_AS = {"'": "\u2019", "@": "\u2019", "`": "\u2018", "\\": "\uff3c"}


def cap_height(font: ImageFont.FreeTypeFont) -> float:
    left, top, right, bottom = font.getbbox("H", anchor="ls")
    return float(-top)


def letter(font: ImageFont.FreeTypeFont, ch: str) -> Image.Image:
    """One cell, coverage 0-255"""
    w, h = CELL_W * SUPERSAMPLE, CELL_H * SUPERSAMPLE
    advance = font.getlength(ch) + 2 * round(WEIGHT * SCALE * SUPERSAMPLE)
    squeeze = min(1.0, w / advance) if advance > 0 else 1.0
    wide = Image.new("L", (int(w / squeeze) + 2, h), 0)
    stroke = round(WEIGHT * SCALE * SUPERSAMPLE)
    ImageDraw.Draw(wide).text((wide.width / 2, BASELINE * SUPERSAMPLE), ch, font=font, fill=255, anchor="ms",
                              stroke_width=stroke, stroke_fill=255)
    cell = wide.resize((w, h), Image.LANCZOS) if squeeze < 1.0 else wide.crop(((wide.width - w) // 2, 0,
                                                                              (wide.width - w) // 2 + w, h))
    return cell.resize((CELL_W, CELL_H), Image.BOX)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("ttf")
    parser.add_argument("--preview", help="also write every letter as one PNG")
    args = parser.parse_args()

    probe = ImageFont.truetype(args.ttf, 1000)
    size = 1000 * (BASELINE - CAP_TOP) * SUPERSAMPLE / cap_height(probe)
    font = ImageFont.truetype(args.ttf, round(size))
    cells = [letter(font, DRAWN_AS.get(chr(c), chr(c))) for c in range(FIRST, LAST + 1)]

    lines = [
        "// Generated by tools/make_font_letters.py from IPA Mincho (third_party/ipa-fonts/): do not edit.",
        "// The game's fonts' English letters drawn again, " + str(SCALE) + " times as fine (port/gs/shared/font_sheet.h).",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace pcr::font_letters {",
        "",
        f"constexpr uint32_t scale = {SCALE};",
        f"constexpr uint32_t cell_width = {CELL_W}, cell_height = {CELL_H};",
        f"constexpr uint32_t first = {FIRST:#x}, count = {LAST - FIRST + 1};",
        "// each letter's coverage, 0 (none) to 255, its rows top down",
        f"static const uint8_t coverage[count][cell_width * cell_height] = {{",
    ]
    for c, cell in zip(range(FIRST, LAST + 1), cells):
        data = cell.tobytes()
        lines.append(f"    {{ // {chr(c)!r}")
        for row in range(CELL_H):
            lines.append("        " + ",".join(str(b) for b in data[row * CELL_W:(row + 1) * CELL_W]) + ",")
        lines.append("    },")
    lines += ["};", "", "} // namespace pcr::font_letters", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} ({len(cells)} letters, {CELL_W} x {CELL_H})")

    if args.preview:
        sheet = Image.new("L", (50 * CELL_W, 2 * CELL_H), 0)
        for n, cell in enumerate(cells):
            sheet.paste(cell, ((n % 50) * CELL_W, (n // 50) * CELL_H))
        sheet.save(args.preview)
    return 0


if __name__ == "__main__":
    sys.exit(main())
