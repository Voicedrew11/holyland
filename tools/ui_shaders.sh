#!/usr/bin/env bash
# The player menu's shaders (port/ui/shaders/ui.vert, ui.frag) compiled to SPIR-V, written as C arrays into
# port/ui/shaders/ui_spirv.h. Run after changing either shader; the header is committed, so building the game
# (and a player's build, which has no shader compiler) never needs glslangValidator.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/../port/ui/shaders"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
glslangValidator -V --target-env vulkan1.0 --vn ui_vert_spirv -o "$work/vert.h" ui.vert >/dev/null
glslangValidator -V --target-env vulkan1.0 --vn ui_frag_spirv -o "$work/frag.h" ui.frag >/dev/null
{
    echo "// Generated by tools/ui_shaders.sh from ui.vert and ui.frag: do not edit."
    echo "#pragma once"
    echo "#include <stdint.h>"
    cat "$work/vert.h" "$work/frag.h"
} >ui_spirv.h
echo "wrote port/ui/shaders/ui_spirv.h"
